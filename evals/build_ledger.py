"""Generate LEDGER.md — the learning dashboard — from lessons/*.md frontmatter.

Deterministic: same lessons in, same file out. `check_repo.py` L18 regenerates and compares,
so a stale dashboard fails the self-audit rather than quietly misrepresenting the project.

WHY THE METRIC IS WHAT IT IS
----------------------------
The obvious dashboard ranks contributors by lesson count. That builds the exact incentive
gradient this project documents in `engines/scoring.md`: when the cheap action and the
rewarded action coincide, the mechanism gets gamed without anyone deciding to cheat. Counting
lessons rewards splitting one finding into five, and filing thin ones.

So the headline number is **classes mechanized** — a lesson that produced a check which
actually exists. That is expensive to fake: L17 already refuses a lesson naming a check that
is not in `check_repo.py`, so inflating this number means writing a real check.

Lessons within one `class` collapse to a single credit. Finding the same shape twice is
valuable evidence and is shown, but it is not two classes.

Run:  python3 evals/build_ledger.py [--check]
"""
from __future__ import annotations

import argparse
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LESSONS = ROOT / "lessons"
OUT = ROOT / "LEDGER.md"

FM = re.compile(r"^---\n(.*?)\n---", re.S)
FIELD = re.compile(r"^([a-z_]+):\s*(.*)$", re.M)


def parse() -> list[dict[str, str]]:
    out: list[dict[str, str]] = []
    for f in sorted(LESSONS.glob("[0-9]*.md")):
        m = FM.match(f.read_text(encoding="utf-8"))
        if not m:
            continue
        d = dict(FIELD.findall(m.group(1)))
        d["file"] = f.name
        title = re.search(r"^# (.+)$", f.read_text(encoding="utf-8"), re.M)
        d["title"] = title.group(1).strip() if title else f.stem
        out.append(d)
    return out


# `found_by` / `missed_by` are a CONTROLLED VOCABULARY, not prose — prose belongs in
# `found_detail` / `missed_detail`, which this file deliberately does not parse. Free text
# split on commas produced contributor rows reading "mid-run" and "unprompted".
AGENTS = {
    "author": "Author / implementer",
    "self-audit": "check_repo.py (automated)",
    "subject-model": "The audited model itself",
    "harness-design": "Harness design review",
    "grok": "Grok (cross-model review)",
    "kimi": "Kimi (cross-model review)",
}


def split_agents(value: str) -> list[str]:
    return [p.strip() for p in value.split(",") if p.strip()]


def label(agent: str) -> str:
    """Known ids get a readable name; anything else is shown verbatim so an external
    contributor's handle appears as they wrote it."""
    return AGENTS.get(agent, agent)


def render(lessons: list[dict[str, str]]) -> str:
    total = len(lessons)
    by_status = Counter(lesson.get("status", "?") for lesson in lessons)
    classes: dict[str, list[dict[str, str]]] = defaultdict(list)
    for lesson in lessons:
        classes[lesson.get("class", "unclassified")].append(lesson)

    mechanized_classes = {
        c for c, ls in classes.items() if any(x.get("status") == "mechanized" for x in ls)
    }

    # Credit: one per CLASS a contributor was first to surface, not one per lesson.
    credit: dict[str, set[str]] = defaultdict(set)
    for cls, ls in classes.items():
        for lesson in ls:
            for who in split_agents(lesson.get("found_by", "unattributed")):
                credit[who].add(cls)

    caught: Counter[str] = Counter()
    for lesson in lessons:
        for who in split_agents(lesson.get("found_by", "unattributed")):
            caught[who] += 1

    missed: Counter[str] = Counter()
    for lesson in lessons:
        for who in split_agents(lesson.get("missed_by", "")):
            missed[who] += 1

    lines: list[str] = []
    a = lines.append

    a("# Learning ledger")
    a("")
    a("<!-- GENERATED by evals/build_ledger.py — do not edit by hand.")
    a("     check_repo.py L18 regenerates this and fails if it is stale. -->")
    a("")
    a("Where VIGIL's improvements actually came from. Every row is backed by a committed")
    a("lesson in [`lessons/`](lessons/README.md) recording something VIGIL, or its own")
    a("self-audit, got **wrong**.")
    a("")
    a(f"**{len(mechanized_classes)} of {len(classes)} classes mechanized** · "
      f"{total} lessons · {by_status.get('open', 0)} open · "
      f"{by_status.get('unmechanizable', 0)} judged unmechanizable")
    a("")

    a("## Contributors")
    a("")
    a("Ranked by **distinct classes surfaced**, not lesson count. Filing five lessons about")
    a("one shape is one class — the metric is deliberately hard to inflate.")
    a("")
    a("| Contributor | Classes | Lessons | Mechanized |")
    a("|---|---|---|---|")
    for who, surfaced in sorted(credit.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        mech = sum(1 for c in surfaced if c in mechanized_classes)
        a(f"| {label(who)} | **{len(surfaced)}** | {caught[who]} | {mech} |")
    a("")

    a("## What caught what")
    a("")
    a("The honest half of the dashboard: which mechanisms earn their keep. A gap found by a")
    a("human reading carefully and one found by an automated check are very different signals.")
    a("")
    a("| Missed it | Times |")
    a("|---|---|")
    for who, n in missed.most_common():
        a(f"| {label(who)} | {n} |")
    a("")

    a("## Classes")
    a("")
    a("| Class | Status | Lesson |")
    a("|---|---|---|")
    for cls in sorted(classes):
        for lesson in classes[cls]:
            badge = {"mechanized": "✅", "open": "⏳", "unmechanizable": "🚫"}.get(
                lesson.get("status", ""), "?"
            )
            check = f" `{lesson['check']}`" if lesson.get("check", "").strip() else ""
            a(f"| {cls} | {badge}{check} | [{lesson['title']}](lessons/{lesson['file']}) |")
    a("")
    a("✅ mechanized — a check now catches this class · ⏳ open — should be mechanized, is not")
    a("yet · 🚫 unmechanizable — genuinely not machine-checkable, with the reason in the lesson")
    a("")
    a("## Contributing")
    a("")
    a("If you found VIGIL wrong, that is the contribution. Send the lesson, not a rule edit —")
    a("evidence is safe to accept from a stranger, an assertion about evidence is not. See")
    a("[`lessons/README.md`](lessons/README.md).")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if LEDGER.md is stale")
    args = ap.parse_args()

    if not LESSONS.is_dir():
        print("no lessons/ directory", file=sys.stderr)
        return 2
    content = render(parse())

    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != content:
            print("LEDGER.md is stale — run: python3 evals/build_ledger.py", file=sys.stderr)
            return 1
        print("LEDGER.md is current")
        return 0

    OUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
